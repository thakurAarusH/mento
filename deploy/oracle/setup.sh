#!/usr/bin/env bash
# MENTO server setup for Ubuntu 24.04 (Oracle Cloud Always Free ARM, or any x86/ARM VM).
# Installs everything MENTO uses, runs it as a service behind Caddy (automatic HTTPS), and backs the database up nightly.
# Usage (on the server, from the copied project folder):  sudo MENTO_HOST=1-2-3-4.sslip.io bash deploy/oracle/setup.sh
# Safe to run again: finished steps are skipped. Never prints or overwrites an existing .env.
set -euo pipefail
HOST="${MENTO_HOST:?set MENTO_HOST, e.g. MENTO_HOST=1-2-3-4.sslip.io}"
SRC="$(cd "$(dirname "$0")/../.." && pwd)"           # the MENTO project copied to the server
APP=/opt/mento DATA=/var/lib/mento OPT=/opt/mento-tools
MODEL="${MENTO_VISION_MODEL:-qwen3-vl:4b-instruct}"
SKIP_SYSTEMD="${SKIP_SYSTEMD:-0}" SKIP_MODEL="${SKIP_MODEL:-0}" SKIP_OLLAMA="${SKIP_OLLAMA:-0}"   # only for testing in a container
NO_AI="${MENTO_NO_AI:-0}"   # 1 = small server: no local vision AI (MENTO reports analysis as unavailable; cloud AI can still be added)
[ "$NO_AI" = 1 ] && SKIP_OLLAMA=1
step() { printf '\n\033[1;31m●\033[0m %s\n' "$*"; }
[ "$(id -u)" = 0 ] || { echo "Run with sudo."; exit 1; }
export DEBIAN_FRONTEND=noninteractive

# Small servers (under 3 GB of memory) get a 4 GB swap file, so building Whisper and transcribing do not run out of memory.
if [ "$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)" -lt 3000 ] && ! swapon --show | grep -q /swapfile && [ "$SKIP_SYSTEMD" != 1 ]; then
  step "Swap file (4 GB) for a small server"
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  sysctl -q vm.swappiness=20; echo 'vm.swappiness=20' > /etc/sysctl.d/99-mento-swap.conf
fi
step "System packages (ffmpeg, PDF text, espeak-ng, Open JTalk, build tools)"
apt-get update -qq
apt-get install -y -qq curl ca-certificates gnupg git unzip rsync sqlite3 build-essential cmake ffmpeg poppler-utils \
  espeak-ng open-jtalk open-jtalk-mecab-naist-jdic debian-keyring debian-archive-keyring apt-transport-https cron >/dev/null

step "Node.js 22"
if ! command -v node >/dev/null || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 22 ]; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null
  apt-get install -y -qq nodejs >/dev/null
fi
node --version

step "Japanese read-aloud voice (HTS voice \"Mei\", Nagoya Institute of Technology, CC BY 3.0)"
mkdir -p "$OPT/voice"
if [ ! -f "$OPT/voice/mei_normal.htsvoice" ]; then
  tmp=$(mktemp -d); curl -fsSL -o "$tmp/mmd.zip" "https://sourceforge.net/projects/mmdagent/files/MMDAgent_Example/MMDAgent_Example-1.8/MMDAgent_Example-1.8.zip/download"
  unzip -q -j "$tmp/mmd.zip" 'MMDAgent_Example-1.8/Voice/mei/mei_normal.htsvoice' -d "$OPT/voice"; rm -rf "$tmp"
fi

step "Whisper (speech-to-text, CPU) and its multilingual model"
if [ ! -x "$OPT/whisper.cpp/build/bin/whisper-cli" ]; then
  rm -rf "$OPT/whisper.cpp"; git clone -q --depth 1 https://github.com/ggml-org/whisper.cpp "$OPT/whisper.cpp"
  cmake -S "$OPT/whisper.cpp" -B "$OPT/whisper.cpp/build" -DCMAKE_BUILD_TYPE=Release -DWHISPER_BUILD_TESTS=OFF >/dev/null
  cmake --build "$OPT/whisper.cpp/build" -j"$(nproc)" --target whisper-cli >/dev/null
fi
mkdir -p "$OPT/models"
[ -f "$OPT/models/ggml-small-q5_1.bin" ] || curl -fsSL -o "$OPT/models/ggml-small-q5_1.bin" https://huggingface.co/ggerganov/whisper.cpp/resolve/main/ggml-small-q5_1.bin

step "Ollama (local vision AI) and the model $MODEL$([ "$NO_AI" = 1 ] && echo " — skipped (MENTO_NO_AI=1)")"
if [ "$SKIP_OLLAMA" != 1 ] && ! command -v ollama >/dev/null; then curl -fsSL https://ollama.com/install.sh | sh >/dev/null; fi
if [ "$SKIP_SYSTEMD" != 1 ] && [ "$SKIP_OLLAMA" != 1 ]; then
  mkdir -p /etc/systemd/system/ollama.service.d
  # one request at a time and only on this machine; keep the model loaded for 30 minutes between analyses
  printf '[Service]\nEnvironment="OLLAMA_HOST=127.0.0.1:11434" "OLLAMA_NUM_PARALLEL=1" "OLLAMA_MAX_LOADED_MODELS=1" "OLLAMA_KEEP_ALIVE=30m"\n' > /etc/systemd/system/ollama.service.d/mento.conf
  systemctl daemon-reload; systemctl enable --now ollama >/dev/null 2>&1; systemctl restart ollama
  [ "$SKIP_MODEL" = 1 ] || { for i in $(seq 1 30); do curl -fs 127.0.0.1:11434/api/version >/dev/null && break; sleep 1; done; ollama pull "$MODEL"; }
fi

step "MENTO application in $APP (data in $DATA)"
id mento >/dev/null 2>&1 || useradd --system --home "$DATA" --shell /usr/sbin/nologin mento
mkdir -p "$APP" "$DATA" "$DATA/backups"
rsync -a --delete --exclude node_modules --exclude data --exclude .env --exclude video --exclude .git "$SRC/" "$APP/"
( cd "$APP" && npm ci --omit=dev --no-audit --no-fund >/dev/null )
if [ ! -f "$APP/.env" ]; then
  PASS=$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)
  cat > "$APP/.env" <<EOF
# MENTO server settings (generated by deploy/oracle/setup.sh). Keep this file private.
MASTER_PASSPHRASE=$PASS
PORT=3000
PUBLIC_URL=https://$HOST
DATA_DIR=$DATA
MAX_VIDEO_MB=200
MAX_RECORDING_SEC=600
RETENTION_DAYS=30
TOKEN_TTL_HOURS=24
ALLOW_SIGNUP=1
$([ "$NO_AI" = 1 ] && echo "# No local vision AI on this small server. To enable AI analysis, set CLOUD_AI and a key (see README, Hybrid AI)." || printf 'OLLAMA_URL=http://127.0.0.1:11434\nOLLAMA_VISION_MODEL=%s' "$MODEL")
# A small CPU server is much slower than a laptop GPU: allow long frames, no pause between them, fewer frames per video.
AI_FRAME_TIMEOUT_MS=600000
AI_FRAME_PAUSE_MS=0
AI_MAX_FRAMES=16
WHISPER_BIN=$OPT/whisper.cpp/build/bin/whisper-cli
WHISPER_MODEL=$OPT/models/ggml-small-q5_1.bin
WHISPER_LANG=auto
WHISPER_THREADS=$(nproc)
OPENJTALK_BIN=/usr/bin/open_jtalk
OPENJTALK_DIC=/var/lib/mecab/dic/open-jtalk/naist-jdic
OPENJTALK_VOICE=$OPT/voice/mei_normal.htsvoice
ESPEAK_BIN=/usr/bin/espeak-ng
CLOUD_AI=off
EOF
  echo "Created $APP/.env — administrator passphrase: $PASS   (shown once; it is stored only in $APP/.env)"
else
  sed -i "s#^PUBLIC_URL=.*#PUBLIC_URL=https://$HOST#" "$APP/.env"; echo "Kept the existing $APP/.env (only PUBLIC_URL updated)."
fi
chown -R mento:mento "$DATA"; chown -R root:mento "$APP"; chmod 640 "$APP/.env"; chmod -R g+rX "$APP"

if [ "$SKIP_SYSTEMD" != 1 ]; then
  step "Service: mento (starts at boot, restarts on failure)"
  cat > /etc/systemd/system/mento.service <<EOF
[Unit]
Description=MENTO
After=network-online.target
Wants=network-online.target
[Service]
User=mento
Group=mento
WorkingDirectory=$APP
ExecStart=/usr/bin/node server.js
Restart=always
RestartSec=3
Environment=NODE_ENV=production
NoNewPrivileges=true
ProtectSystem=full
ReadWritePaths=$DATA
[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload; systemctl enable --now mento >/dev/null 2>&1; systemctl restart mento

  step "HTTPS with Caddy (free Let's Encrypt certificate for $HOST)"
  if ! command -v caddy >/dev/null; then
    curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/gpg.key | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt > /etc/apt/sources.list.d/caddy-stable.list
    apt-get update -qq; apt-get install -y -qq caddy >/dev/null
  fi
  cat > /etc/caddy/Caddyfile <<EOF
$HOST {
	encode gzip
	request_body {
		max_size 250MB
	}
	reverse_proxy 127.0.0.1:3000 {
		flush_interval -1
	}
}
EOF
  systemctl enable --now caddy >/dev/null 2>&1; systemctl reload caddy || systemctl restart caddy

  step "Firewall: allow web traffic (ports 80 and 443)"
  for p in 80 443; do iptables -C INPUT -p tcp --dport $p -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p tcp --dport $p -m state --state NEW -j ACCEPT; done
  if command -v netfilter-persistent >/dev/null; then netfilter-persistent save >/dev/null 2>&1 || true; fi
fi

step "Nightly database backup (03:30, last 14 kept in $DATA/backups)"
cat > /usr/local/bin/mento-backup <<EOF
#!/bin/sh
# Consistent copy of the MENTO database; videos stay in $DATA/rec (covered by Oracle volume backups).
set -e
sqlite3 "$DATA/monozukuri.db" ".backup '$DATA/backups/mento-\$(date +%F).db'"
ls -1t "$DATA"/backups/mento-*.db | tail -n +15 | xargs -r rm -f
EOF
chmod 755 /usr/local/bin/mento-backup
echo "30 3 * * * mento /usr/local/bin/mento-backup" > /etc/cron.d/mento-backup

step "Check"
if [ "$SKIP_SYSTEMD" != 1 ]; then
  for i in $(seq 1 20); do curl -fs 127.0.0.1:3000/api/health >/dev/null && break; sleep 1; done
  curl -fs 127.0.0.1:3000/api/health && echo
  echo "MENTO is running. Open https://$HOST (the certificate can take a minute the first time)."
fi
